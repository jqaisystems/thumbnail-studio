// cleanmeta.js - remove AI provenance metadata without touching the picture.
//
// Images generated through chatgpt.com arrive carrying a C2PA "Content
// Credentials" block (a caBX chunk in PNG, an APP11 JUMBF segment in JPEG,
// a C2PA chunk in WebP). It is roughly 25KB per file and it travels into
// every ZIP the studio hands over. This strips it.
//
// The picture data is never re-encoded. Only container-level metadata blocks
// are dropped, and a hash of the encoded image payload is compared before and
// after; if it moved by a single byte, nothing is written.
//
// Ported from the `remove-ai-image-metadata` skill's clean_image_metadata.py,
// which stays the reference implementation and covers more formats plus
// field-level XMP surgery: https://github.com/jqaisystems/jqai-ai-skills
//
// Deliberate difference from the Python original: a JPEG Exif APP1 segment is
// never removed here, even when it matches a marker. Dropping the whole EXIF
// block can take orientation with it and silently rotate someone's photo.
// Generated images have no camera EXIF, so nothing of value is kept behind.

const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const crypto = require('crypto');

const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const SUPPORTED = /\.(png|jpe?g|webp)$/i;

// Lowercased, with NUL bytes squeezed out before matching, so UTF-16 text hits too.
const AI_MARKERS = [
  'openai', 'gpt image', 'chatgpt', 'dall-e', 'dall e', 'dalle',
  'c2pa', 'content credentials', 'ai-generated', 'ai generated',
  'generated by ai', 'generative ai', 'midjourney', 'stable diffusion',
  'adobe firefly',
];

class ImageMetadataError extends Error {}

function markerIn(buf) {
  // Squeeze NULs so UTF-16LE/BE text matches the same ASCII markers.
  const text = buf.toString('latin1').replace(/\0/g, '').toLowerCase();
  return AI_MARKERS.find((m) => text.includes(m)) || null;
}

function sha256(parts) {
  const h = crypto.createHash('sha256');
  for (const p of parts) h.update(p);
  return h.digest('hex');
}

function detectFormat(data, source) {
  if (data.length >= 8 && data.subarray(0, 8).equals(PNG_SIGNATURE)) return 'PNG';
  if (data.length >= 2 && data[0] === 0xff && data[1] === 0xd8) return 'JPEG';
  if (data.length >= 12 && data.subarray(0, 4).toString('latin1') === 'RIFF'
      && data.subarray(8, 12).toString('latin1') === 'WEBP') return 'WebP';
  throw new ImageMetadataError(`${source}: unsupported image container`);
}

/* ---------- PNG ----------------------------------------------------------- */

const PNG_TEXT_CHUNKS = new Set(['tEXt', 'zTXt', 'iTXt']);

function parsePng(data, source) {
  const chunks = [];
  let pos = PNG_SIGNATURE.length;
  let sawIend = false;
  while (pos + 12 <= data.length) {
    const start = pos;
    const length = data.readUInt32BE(pos);
    const type = data.subarray(pos + 4, pos + 8).toString('latin1');
    const payloadStart = pos + 8;
    const payloadEnd = payloadStart + length;
    const end = payloadEnd + 4;
    if (end > data.length) throw new ImageMetadataError(`${source}: truncated PNG chunk`);
    const payload = data.subarray(payloadStart, payloadEnd);
    const stored = data.readUInt32BE(payloadEnd);
    // The PNG CRC covers the type bytes plus the payload.
    if (crc32(data.subarray(pos + 4, payloadEnd)) !== stored) {
      throw new ImageMetadataError(`${source}: invalid CRC in ${type}`);
    }
    chunks.push({ type, payload, raw: data.subarray(start, end) });
    pos = end;
    if (type === 'IEND') { sawIend = true; break; }
  }
  if (!sawIend || pos !== data.length || !chunks.length || chunks[0].type !== 'IHDR') {
    throw new ImageMetadataError(`${source}: malformed PNG structure`);
  }
  return chunks;
}

// zlib.crc32 only exists from Node 22, and the studio targets Node 20+.
let CRC_TABLE = null;
function crc32(buf) {
  if (!CRC_TABLE) {
    CRC_TABLE = new Int32Array(256);
    for (let n = 0; n < 256; n++) {
      let c = n;
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
      CRC_TABLE[n] = c;
    }
  }
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

// Decode a text chunk far enough to search it. Never throws: an undecodable
// payload is searched raw rather than skipped.
function pngText(type, payload) {
  try {
    if (type === 'tEXt') return payload;
    const nul = payload.indexOf(0);
    if (nul < 0) return payload;
    if (type === 'zTXt') {
      if (payload[nul + 1] !== 0) return payload;
      return Buffer.concat([payload.subarray(0, nul), zlib.inflateSync(payload.subarray(nul + 2))]);
    }
    if (type === 'iTXt') {
      const compressed = payload[nul + 1];
      const method = payload[nul + 2];
      let p = nul + 3;
      const langEnd = payload.indexOf(0, p);
      if (langEnd < 0) return payload;
      const transEnd = payload.indexOf(0, langEnd + 1);
      if (transEnd < 0) return payload;
      const text = payload.subarray(transEnd + 1);
      if (compressed === 1 && method === 0) {
        return Buffer.concat([payload.subarray(0, transEnd), zlib.inflateSync(text)]);
      }
      return payload;
    }
  } catch {
    return payload;
  }
  return payload;
}

function pngReason(chunk) {
  if (chunk.type === 'caBX') return 'C2PA/Content Credentials caBX block';
  // Bit 5 of the first byte lowercase means ancillary. Critical chunks
  // (IHDR, PLTE, IDAT, IEND) are never candidates.
  const ancillary = (chunk.type.charCodeAt(0) & 0x20) !== 0;
  if (!ancillary) return null;
  // iCCP, gAMA, cHRM, sRGB and friends affect how the picture renders.
  if (!PNG_TEXT_CHUNKS.has(chunk.type) && chunk.type !== 'eXIf') return null;
  const searchable = PNG_TEXT_CHUNKS.has(chunk.type) ? pngText(chunk.type, chunk.payload) : chunk.payload;
  const marker = markerIn(searchable);
  return marker ? `AI metadata marker: ${marker}` : null;
}

function cleanPng(data, source) {
  const chunks = parsePng(data, source);
  const kept = [];
  const removals = [];
  for (const chunk of chunks) {
    const reason = pngReason(chunk);
    if (reason) removals.push({ label: chunk.type, bytes: chunk.payload.length, reason });
    else kept.push(chunk);
  }
  const ihdr = chunks[0].payload;
  return {
    format: 'PNG',
    dimensions: `${ihdr.readUInt32BE(0)}x${ihdr.readUInt32BE(4)}`,
    removals,
    cleaned: Buffer.concat([PNG_SIGNATURE, ...kept.map((c) => c.raw)]),
    encodedHash: sha256(chunks.filter((c) => c.type === 'IDAT').map((c) => c.payload)),
  };
}

/* ---------- JPEG ---------------------------------------------------------- */

const JPEG_STANDALONE = new Set([0x01, 0xd8, 0xd9, 0xd0, 0xd1, 0xd2, 0xd3, 0xd4, 0xd5, 0xd6, 0xd7]);
const JPEG_SOF = new Set([0xc0, 0xc1, 0xc2, 0xc3, 0xc5, 0xc6, 0xc7, 0xc9, 0xca, 0xcb, 0xcd, 0xce, 0xcf]);
const EXIF_HEADER = Buffer.from('Exif\0\0', 'latin1');

function parseJpeg(data, source) {
  const segments = [{ marker: 0xd8, payload: Buffer.alloc(0), raw: data.subarray(0, 2) }];
  let pos = 2;
  while (pos < data.length) {
    const start = pos;
    if (data[pos] !== 0xff) throw new ImageMetadataError(`${source}: expected JPEG marker at ${pos}`);
    while (pos < data.length && data[pos] === 0xff) pos++;
    if (pos >= data.length) throw new ImageMetadataError(`${source}: truncated JPEG marker`);
    const marker = data[pos];
    pos++;
    if (marker === 0x00) throw new ImageMetadataError(`${source}: stuffed byte before scan data`);
    if (JPEG_STANDALONE.has(marker)) {
      segments.push({ marker, payload: Buffer.alloc(0), raw: data.subarray(start, pos) });
      if (marker === 0xd9) {
        if (pos !== data.length) throw new ImageMetadataError(`${source}: trailing data after EOI`);
        return segments;
      }
      continue;
    }
    if (pos + 2 > data.length) throw new ImageMetadataError(`${source}: truncated segment length`);
    const length = data.readUInt16BE(pos);
    if (length < 2 || pos + length > data.length) {
      throw new ImageMetadataError(`${source}: invalid JPEG segment length`);
    }
    const end = pos + length;
    const payload = data.subarray(pos + 2, end);
    if (marker === 0xda) {
      // Everything from the scan header to the end of file, entropy-coded data included.
      segments.push({ marker, payload, raw: data.subarray(start) });
      return segments;
    }
    segments.push({ marker, payload, raw: data.subarray(start, end) });
    pos = end;
  }
  throw new ImageMetadataError(`${source}: JPEG ended before scan or EOI`);
}

function jpegLabel(marker) {
  if (marker >= 0xe0 && marker <= 0xef) return `APP${marker - 0xe0}`;
  if (marker === 0xfe) return 'COM';
  return `FF${marker.toString(16).toUpperCase().padStart(2, '0')}`;
}

function jpegReason(segment) {
  const { marker, payload } = segment;
  // APP11 carries JUMBF, which is how C2PA rides in a JPEG.
  if (marker === 0xeb && (payload.subarray(0, 2).toString('latin1') === 'JP' || markerIn(payload))) {
    return 'C2PA/JUMBF APP11 provenance segment';
  }
  if (marker === 0xe1 || marker === 0xed || marker === 0xfe) {
    // Never strip Exif: orientation and other rendering fields live alongside.
    if (marker === 0xe1 && payload.subarray(0, 6).equals(EXIF_HEADER)) return null;
    const found = markerIn(payload);
    if (found) return `AI metadata marker: ${found}`;
  }
  return null;
}

function cleanJpeg(data, source) {
  const segments = parseJpeg(data, source);
  const kept = [];
  const removals = [];
  for (const segment of segments) {
    const reason = jpegReason(segment);
    if (reason) removals.push({ label: jpegLabel(segment.marker), bytes: segment.payload.length, reason });
    else kept.push(segment);
  }
  let dimensions = 'unknown';
  for (const s of segments) {
    if (JPEG_SOF.has(s.marker) && s.payload.length >= 5) {
      dimensions = `${s.payload.readUInt16BE(3)}x${s.payload.readUInt16BE(1)}`;
      break;
    }
  }
  const scan = segments.find((s) => s.marker === 0xda);
  return {
    format: 'JPEG',
    dimensions,
    removals,
    cleaned: Buffer.concat(kept.map((s) => s.raw)),
    encodedHash: sha256([scan ? scan.raw : Buffer.alloc(0)]),
  };
}

/* ---------- WebP ---------------------------------------------------------- */

const WEBP_FUNCTIONAL = new Set(['ICCP', 'ANIM', 'ANMF', 'ALPH', 'VP8 ', 'VP8L']);

function parseWebp(data, source) {
  const declared = data.readUInt32LE(4) + 8;
  if (declared !== data.length) throw new ImageMetadataError(`${source}: WebP RIFF size mismatch`);
  const chunks = [];
  let pos = 12;
  while (pos + 8 <= data.length) {
    const start = pos;
    const type = data.subarray(pos, pos + 4).toString('latin1');
    const length = data.readUInt32LE(pos + 4);
    const payloadStart = pos + 8;
    const payloadEnd = payloadStart + length;
    const end = payloadEnd + (length & 1);
    if (end > data.length) throw new ImageMetadataError(`${source}: truncated WebP chunk`);
    chunks.push({ type, payload: data.subarray(payloadStart, payloadEnd), raw: data.subarray(start, end) });
    pos = end;
  }
  if (pos !== data.length) throw new ImageMetadataError(`${source}: malformed WebP chunk layout`);
  return chunks;
}

function riffChunk(type, payload) {
  const head = Buffer.alloc(8);
  head.write(type, 0, 'latin1');
  head.writeUInt32LE(payload.length, 4);
  return payload.length & 1
    ? Buffer.concat([head, payload, Buffer.alloc(1)])
    : Buffer.concat([head, payload]);
}

function webpReason(chunk) {
  if (chunk.type === 'C2PA') return 'C2PA RIFF provenance chunk';
  if (chunk.type === 'EXIF' || chunk.type === 'XMP ') {
    const found = markerIn(chunk.payload);
    if (found) return `AI metadata marker: ${found}`;
  }
  if (!WEBP_FUNCTIONAL.has(chunk.type) && chunk.type !== 'VP8X') {
    const found = markerIn(chunk.payload);
    if (found) return `AI metadata marker in ancillary chunk: ${found}`;
  }
  return null;
}

function cleanWebp(data, source) {
  const chunks = parseWebp(data, source);
  const kept = [];
  const removals = [];
  for (const chunk of chunks) {
    const reason = webpReason(chunk);
    if (reason) removals.push({ label: chunk.type.trim(), bytes: chunk.payload.length, reason });
    else kept.push({ ...chunk });
  }
  // VP8X advertises which optional chunks exist. Leaving a flag set for a
  // chunk we just removed produces a file some decoders reject.
  const remaining = new Set(kept.map((c) => c.type));
  for (const chunk of kept) {
    if (chunk.type === 'VP8X' && chunk.payload.length >= 10) {
      const payload = Buffer.from(chunk.payload);
      if (!remaining.has('EXIF')) payload[0] &= ~0x08;
      if (!remaining.has('XMP ')) payload[0] &= ~0x04;
      chunk.payload = payload;
      chunk.raw = riffChunk('VP8X', payload);
    }
  }
  let dimensions = 'unknown';
  const vp8x = chunks.find((c) => c.type === 'VP8X' && c.payload.length >= 10);
  if (vp8x) {
    const p = vp8x.payload;
    dimensions = `${1 + (p[4] | (p[5] << 8) | (p[6] << 16))}x${1 + (p[7] | (p[8] << 8) | (p[9] << 16))}`;
  }
  const body = Buffer.concat([Buffer.from('WEBP', 'latin1'), ...kept.map((c) => c.raw)]);
  const size = Buffer.alloc(4);
  size.writeUInt32LE(body.length, 0);
  return {
    format: 'WebP',
    dimensions,
    removals,
    cleaned: Buffer.concat([Buffer.from('RIFF', 'latin1'), size, body]),
    encodedHash: sha256(chunks.filter((c) => WEBP_FUNCTIONAL.has(c.type)).map((c) => c.payload)),
  };
}

/* ---------- dispatch ------------------------------------------------------ */

function cleanBytes(data, source) {
  const format = detectFormat(data, source);
  if (format === 'PNG') return cleanPng(data, source);
  if (format === 'JPEG') return cleanJpeg(data, source);
  return cleanWebp(data, source);
}

function encodedHashFor(data, source) {
  return cleanBytes(data, source).encodedHash;
}

/* ---------- public API ---------------------------------------------------- */

// A synchronous pause. Only ever used between rename retries.
function sleep(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

// Replace a file's bytes, atomically where the OS allows it.
//
// The temp-file-then-rename dance is the safe way to do this, but on Windows
// rename fails with EPERM while any handle to the target is still open, and
// multer's upload stream is often not closed yet when we are called. Those
// failures clear in milliseconds, so retry before falling back to an in-place
// write, and keep the original bytes to put back if that write dies partway.
function writeReplace(file, data, original) {
  const tmp = path.join(path.dirname(file), `.${path.basename(file)}.cleanmeta.tmp`);
  fs.writeFileSync(tmp, data);
  const retryable = new Set(['EPERM', 'EBUSY', 'EACCES']);

  for (let attempt = 0; attempt < 12; attempt++) {
    try {
      fs.renameSync(tmp, file);
      return;
    } catch (err) {
      if (!retryable.has(err.code) || attempt === 11) break;
      sleep(25);
    }
  }

  try {
    fs.writeFileSync(file, data);
    fs.rmSync(tmp, { force: true });
  } catch (err) {
    // Put the original back rather than leave a half-written image behind.
    try { fs.writeFileSync(file, original); } catch {}
    try { fs.rmSync(tmp, { force: true }); } catch {}
    throw err;
  }
}

// Read-only. Returns what WOULD be removed.
function inspect(file) {
  const result = cleanBytes(fs.readFileSync(file), file);
  return {
    file,
    format: result.format,
    dimensions: result.dimensions,
    findings: result.removals,
  };
}

// Removes AI provenance in place. Writes nothing if there is nothing to
// remove, and refuses to write if the encoded picture data moved at all.
function cleanFile(file) {
  const original = fs.readFileSync(file);
  const result = cleanBytes(original, file);
  if (!result.removals.length) {
    return { file, format: result.format, cleaned: false, removed: [], bytesSaved: 0 };
  }

  // Three gates, all of them before anything touches the real file.
  const reparsed = cleanBytes(result.cleaned, file);
  if (reparsed.removals.length) {
    throw new ImageMetadataError(`${file}: matching metadata remains after cleaning`);
  }
  if (reparsed.encodedHash !== result.encodedHash) {
    throw new ImageMetadataError(`${file}: encoded image payload changed`);
  }

  writeReplace(file, result.cleaned, original);

  // And once more against what actually landed on disk.
  const written = fs.readFileSync(file);
  if (encodedHashFor(written, file) !== result.encodedHash) {
    throw new ImageMetadataError(`${file}: written encoded image payload changed`);
  }

  return {
    file,
    format: result.format,
    cleaned: true,
    removed: result.removals,
    bytesSaved: original.length - result.cleaned.length,
  };
}

function listImages(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir)
    .filter((f) => SUPPORTED.test(f))
    .map((f) => path.join(dir, f));
}

// Inspect every supported image in a folder. Unreadable or unsupported files
// are reported, never thrown, so one odd file cannot block a whole sweep.
function inspectDir(dir) {
  const out = { files: 0, dirty: 0, findings: 0, items: [], errors: [] };
  for (const file of listImages(dir)) {
    out.files++;
    try {
      const r = inspect(file);
      if (r.findings.length) {
        out.dirty++;
        out.findings += r.findings.length;
        out.items.push({ name: path.basename(file), format: r.format, findings: r.findings });
      }
    } catch (err) {
      out.errors.push({ name: path.basename(file), error: String(err.message || err) });
    }
  }
  return out;
}

function cleanDir(dir) {
  const out = { files: 0, cleaned: 0, removed: 0, bytesSaved: 0, items: [], errors: [] };
  for (const file of listImages(dir)) {
    out.files++;
    try {
      const r = cleanFile(file);
      if (r.cleaned) {
        out.cleaned++;
        out.removed += r.removed.length;
        out.bytesSaved += r.bytesSaved;
        out.items.push({ name: path.basename(file), removed: r.removed, bytesSaved: r.bytesSaved });
      }
    } catch (err) {
      out.errors.push({ name: path.basename(file), error: String(err.message || err) });
    }
  }
  return out;
}

module.exports = {
  inspect, cleanFile, inspectDir, cleanDir, ImageMetadataError, AI_MARKERS, SUPPORTED,
};
